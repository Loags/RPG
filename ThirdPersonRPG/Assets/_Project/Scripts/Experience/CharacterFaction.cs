namespace LB
{
    /// <summary>
    /// Represents the faction/team a character belongs to
    /// </summary>
    public enum CharacterFaction
    {
        /// <summary>
        /// Player and their allies
        /// </summary>
        PlayerFaction,
        
        /// <summary>
        /// Hostile enemies
        /// </summary>
        EnemyFaction,
        
        /// <summary>
        /// Neutral characters that don't participate in combat
        /// </summary>
        Neutral
    }
} 